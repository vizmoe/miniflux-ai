// Run with a local copy of the IANA Language Subtag Registry as the sole argument.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const raw = readFileSync(process.argv[2], 'utf8');
const date = /^File-Date: (\d{4}-\d{2}-\d{2})/m.exec(raw)?.[1];
const codes = raw
  .split('%%')
  .filter((record) => /^Type: language$/m.test(record))
  .map((record) => /^Subtag: ([a-z]{2,3})$/m.exec(record)?.[1])
  .filter((code) => code && !['und', 'mul', 'zxx'].includes(code))
  .sort();
if (!date || codes.length < 8000 || new Set(codes).size !== codes.length)
  throw new Error('invalid_language_registry');
const lines = [];
for (let i = 0; i < codes.length; i += 20)
  lines.push(codes.slice(i, i + 20).join(' '));
writeFileSync(
  new URL('../src/lang/registry.ts', import.meta.url),
  `// Generated by scripts/update-language-registry.mjs; do not edit by hand.
// https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry
// File-Date: ${date}; SHA-256: ${createHash('sha256').update(raw).digest('hex')}
// Registered primary languages, including aliases; excludes private ranges, mul, zxx, und.
export const registeredLanguages = new Set(\`
${lines.join('\n')}
\`.trim().split(/\\s+/));
`,
);
